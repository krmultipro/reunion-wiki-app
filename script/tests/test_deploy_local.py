"""Exercise the local deployment with disposable Git repositories and fake SSH."""
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


class LocalDeploymentTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.repo = self.root / 'repo'
        self.repo.mkdir()
        self.capture = self.root / 'capture'
        self.capture.mkdir()
        for folder in ('script', 'tests', 'reunion_wiki', 'templates', 'static'):
            (self.repo / folder).mkdir()
        for name in ('deploy-dev.sh', 'script/run_app_tests.py', 'script/deploy_artifact.py'):
            shutil.copyfile(ROOT / name, self.repo / name)
        (self.repo / 'script/deploy-dev-remote.sh').write_text('# committed remote\n')
        for name in ('app.py', 'migrate.py', 'reunion_wiki/__init__.py', 'tests/__init__.py', 'Dockerfile', '.dockerignore', 'requirements.txt', 'templates/base.html', 'static/safe.css'):
            (self.repo / name).touch()
        (self.repo / 'tests/test_example.py').write_text('import unittest\nclass Example(unittest.TestCase):\n def test_ok(self): self.assertTrue(True)\n')
        (self.repo / '.gitignore').write_text('.venv/\n__pycache__/\n*.pyc\n.env\n')
        self.git('init', '-b', 'dev')
        self.git('config', 'user.name', 'Deployment test')
        self.git('config', 'user.email', 'test@example.invalid')
        self.git('add', '.')
        self.git('commit', '-m', 'fixture')
        binaries = self.root / 'bin'
        binaries.mkdir()
        self.executable(binaries / 'ssh', '''echo ssh >> "$CAPTURE/trace"
if [[ ! -e "$CAPTURE/connected" ]]; then touch "$CAPTURE/connected"; exit 0; fi
exit 77
''')
        self.executable(binaries / 'scp', 'echo scp >> "$CAPTURE/trace"\ncp "$1" "$CAPTURE/$(basename "$2")"\n')
        (self.repo / '.venv/bin').mkdir(parents=True)
        self.executable(self.repo / '.venv/bin/python', '''echo "$*" >> "$CAPTURE/python"
if [[ "$FAIL_STAGE" == syntax && "$2" == compileall ]]; then exit 1; fi
if [[ "$FAIL_STAGE" == tests && "$1" == script/run_app_tests.py ]]; then exit 1; fi
if [[ "$MUTATE_WORKTREE" == yes && "$1" == script/run_app_tests.py ]]; then
  echo changed > "$WORKTREE/script/deploy-dev-remote.sh"
  echo '# generated by tests' > script/deploy-dev-remote.sh
fi
exec "$REAL_PYTHON" "$@"
''')
        self.env = dict(os.environ, PATH=str(binaries) + ':' + os.environ['PATH'],
                        CAPTURE=str(self.capture), FAIL_STAGE='', MUTATE_WORKTREE='',
                        REAL_PYTHON=sys.executable, WORKTREE=str(self.repo))

    def executable(self, path, body):
        path.write_text('#!/bin/bash\n' + body)
        path.chmod(0o755)

    def git(self, *args):
        return subprocess.run(['git', '-C', str(self.repo), *args], check=True, capture_output=True, text=True)

    def run_script(self, *args):
        return subprocess.run(['bash', str(self.repo / 'deploy-dev.sh'), *args], capture_output=True, text=True, env=self.env)

    def assert_blocked(self, *args):
        result = self.run_script(*args)
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertFalse((self.capture / 'trace').exists(), result.stdout)
        return result

    def test_dirty_tracked_file_blocks(self):
        (self.repo / 'app.py').write_text('# unfinished\n')
        self.assertIn('commite', self.assert_blocked().stderr)

    def test_untracked_file_blocks(self):
        (self.repo / 'unfinished.py').touch()
        self.assert_blocked()

    def test_missing_environment_blocks(self):
        (self.repo / '.venv/bin/python').unlink()
        self.assertIn('absent', self.assert_blocked().stderr)

    def test_syntax_failure_blocks(self):
        self.env['FAIL_STAGE'] = 'syntax'
        self.assertIn('syntaxe', self.assert_blocked().stderr)

    def test_test_failure_blocks_even_with_migration_option(self):
        self.env['FAIL_STAGE'] = 'tests'
        self.assertIn('tests applicatifs', self.assert_blocked('--allow-db-change').stderr)

    def test_empty_test_suite_blocks(self):
        self.git('rm', 'tests/test_example.py')
        self.git('commit', '-m', 'empty suite')
        self.assertIn('Aucun test', self.assert_blocked().stderr)

    def test_wrong_branch_blocks(self):
        self.git('switch', '-c', 'other')
        self.assertIn('branche dev', self.assert_blocked().stderr)

    def test_extra_arguments_block(self):
        self.assertIn('Usage', self.assert_blocked('--allow-db-change', 'extra').stderr)

    def test_real_syntax_error_blocks(self):
        (self.repo / 'app.py').write_text('def broken(\n')
        self.git('add', 'app.py')
        self.git('commit', '-m', 'syntax error fixture')
        self.assertIn('syntaxe', self.assert_blocked().stderr)

    def test_real_assertion_failure_blocks(self):
        path = self.repo / 'tests/test_example.py'
        path.write_text(path.read_text().replace('assertTrue(True)', 'assertTrue(False)'))
        self.git('add', 'tests/test_example.py')
        self.git('commit', '-m', 'failing test fixture')
        self.assertIn('FAILED', self.assert_blocked().stderr)

    def test_archive_and_remote_script_use_commit_even_if_worktree_changes(self):
        (self.repo / '.env').write_text('PRIVATE_VALUE=excluded\n')
        self.env['MUTATE_WORKTREE'] = 'yes'
        result = self.run_script()
        self.assertEqual(result.returncode, 77, result.stdout + result.stderr)
        self.assertEqual((self.capture / 'deploy.sh').read_text(), '# committed remote\n')
        with tarfile.open(self.capture / 'source.tar.gz') as archive:
            self.assertEqual(archive.extractfile('./script/deploy-dev-remote.sh').read(), b'# committed remote\n')
            self.assertFalse(any('.env' in name or '__pycache__' in name for name in archive.getnames()))
        self.assertEqual((self.capture / 'trace').read_text().splitlines(), ['ssh', 'scp', 'scp', 'ssh'])

    def test_private_force_added_content_never_enters_archive(self):
        for name in ('maquettes/apercu-prive/README.md', 'monitoring/private.txt', 'sephora.jpeg',
                     'static/uploads/private.jpg', 'static/.env.production', 'static/sephora.jpeg'):
            path = self.repo / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text('private fixture')
            self.git('add', '-f', name)
        self.git('commit', '-m', 'private fixture')
        result = self.run_script()
        self.assertEqual(result.returncode, 77, result.stdout + result.stderr)
        with tarfile.open(self.capture / 'source.tar.gz') as archive:
            names = archive.getnames()
            self.assertFalse(any('private' in n or 'sephora' in n or '.env' in n or 'monitoring' in n for n in names))
